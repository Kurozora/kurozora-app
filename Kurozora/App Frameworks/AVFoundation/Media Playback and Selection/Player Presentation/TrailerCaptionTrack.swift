import Foundation

/// A subtitle track a trailer's page offers.
struct TrailerCaptionTrack: Equatable {
	/// A timed line of a subtitle track.
	struct Cue: Equatable {
		/// The second the line appears at.
		let start: Double

		/// The second the line disappears at.
		let end: Double

		/// The line's text.
		let text: String
	}

	// MARK: - Properties
	/// The language the track is written in.
	let languageCode: String

	/// The name the page gives the track.
	let name: String

	/// A Boolean value indicating whether the track was generated by speech recognition.
	let isAutoGenerated: Bool

	/// The address the track's text is fetched from.
	let address: String

	// MARK: - Functions
	/// Reads the timed lines out of a WebVTT document.
	///
	/// - Parameter webVTT: The document's text.
	///
	/// - Returns: The lines in playback order.
	static func cues(fromWebVTT webVTT: String) -> [Cue] {
		var cues: [Cue] = []
		var timing: (start: Double, end: Double)?
		var markupLines: [String] = []

		func closeCue() {
			if let timing = timing, !markupLines.isEmpty {
				cues.append(contentsOf: Self.timedCues(from: markupLines.joined(separator: "\n"), start: timing.start, end: timing.end))
			}

			timing = nil
			markupLines = []
		}

		for rawLine in webVTT.components(separatedBy: .newlines) {
			let line = rawLine.trimmingCharacters(in: .whitespaces)

			if line.isEmpty {
				closeCue()
				continue
			}

			if line.contains("-->") {
				closeCue()

				let parts = line.components(separatedBy: "-->")
				guard parts.count == 2, let start = Self.seconds(fromTimestamp: parts[0]), let end = Self.seconds(fromTimestamp: parts[1]) else { continue }

				timing = (start, end)
				continue
			}

			guard timing != nil else { continue }
			markupLines.append(line)
		}

		closeCue()
		return cues
	}

	/// Splits a cue on the timestamps written between its words.
	///
	/// - Parameters:
	///    - markup: The cue's lines as written in the document.
	///    - start: The second the cue appears at.
	///    - end: The second the cue disappears at.
	///
	/// - Returns: A line per timestamp carrying the words spoken so far.
	private static func timedCues(from markup: String, start: Double, end: Double) -> [Cue] {
		var pieces: [(start: Double, text: String)] = [(start, "")]
		var tag = ""
		var isInsideTag = false

		for character in markup {
			if character == "<" {
				isInsideTag = true
				tag = ""
			} else if character == ">" {
				isInsideTag = false

				if tag.contains(":"), let time = Self.seconds(fromTimestamp: tag) {
					pieces.append((time, ""))
				}
			} else if isInsideTag {
				tag.append(character)
			} else {
				pieces[pieces.count - 1].text.append(character)
			}
		}

		var cues: [Cue] = []
		var shownText = ""

		for (index, piece) in pieces.enumerated() {
			shownText += piece.text

			let pieceEnd = index + 1 < pieces.count ? pieces[index + 1].start : end
			let text = Self.decodingEntities(in: shownText).trimmingCharacters(in: .whitespacesAndNewlines)
			guard !text.isEmpty, piece.start < pieceEnd else { continue }

			cues.append(Cue(start: piece.start, end: pieceEnd, text: text))
		}

		return cues
	}

	/// Returns the seconds a WebVTT timestamp stands for.
	///
	/// - Parameter timestamp: The timestamp with any cue settings after it.
	///
	/// - Returns: The seconds from the start of the track.
	private static func seconds(fromTimestamp timestamp: String) -> Double? {
		guard let clock = timestamp.split(separator: " ").first else { return nil }

		var seconds = 0.0

		for part in clock.split(separator: ":") {
			guard let value = Double(part) else { return nil }
			seconds = seconds * 60.0 + value
		}

		return seconds
	}

	/// Returns the text with its character entities written out.
	///
	/// - Parameter text: The text as written in the document.
	///
	/// - Returns: The readable text.
	private static func decodingEntities(in text: String) -> String {
		let entities = ["&amp;": "&", "&lt;": "<", "&gt;": ">", "&quot;": "\"", "&#39;": "'", "&nbsp;": " "]

		return entities.reduce(text) { decoded, entity in
			decoded.replacingOccurrences(of: entity.key, with: entity.value)
		}
	}
}
